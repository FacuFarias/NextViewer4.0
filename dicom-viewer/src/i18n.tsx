export function localizeError(t: Translator, error: unknown, fallbackKey: string): string {
  const message = error instanceof Error ? error.message : typeof error === 'string' ? error : '';
  const key = errorKeyByMessage[message];
  return key ? t(key) : message || t(fallbackKey);
}

interface TranslationContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translator;
}

const TranslationContext = createContext<TranslationContextValue | null>(null);

export const LanguageProvider: FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => getConfig().language);

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = translate(language, 'app.documentTitle');
  }, [language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    updateConfig({ language: nextLanguage });
  }, []);

  const value = useMemo<TranslationContextValue>(() => ({
    language,
    setLanguage,
    t: (key, variables) => translate(language, key, variables),
  }), [language, setLanguage]);

  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
};

export function useTranslation(): TranslationContextValue {
  const context = useContext(TranslationContext);
  if (!context) {
    throw new Error('useTranslation must be used inside LanguageProvider');
  }
  return context;
}

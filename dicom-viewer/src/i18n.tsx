function interpolate(template: string, variables?: TranslationVariables): string {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    variables[name] === undefined ? `{${name}}` : String(variables[name])
  );
}

export function translate(language: Language, key: string, variables?: TranslationVariables): string {
  const template = messages[language][key] || messages.en[key] || key;
  return interpolate(template, variables);
}

